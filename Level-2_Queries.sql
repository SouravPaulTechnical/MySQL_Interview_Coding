USE interview_practice;

-- Section A – Basic SELECT queries
-- =================================
-- 1. Retrieve all columns and records from the sales_data table.
SELECT * FROM sales_data; 

-- Section A – Aggregate functions
-- ================================

-- Focus: COUNT(), SUM(), AVG(), MIN(), MAX()

-- 1. Find the total number of orders in the table.
SELECT COUNT(order_id) FROM sales_data;

-- Calculate the total revenue generated from all orders.
-- Hint: Consider quantity, unit price, and discount percentage.
SELECT SUM(quantity * unit_price * (100 - discount_percent)/100) AS total_revenue FROM sales_data;

-- 3. Find the average unit price of all products.
SELECT AVG(unit_price) AS average_unit_price FROM sales_data;

-- 4. Find the maximum and minimum unit price in the table.
SELECT MAX(unit_price) as maximum_unit_price, MIN(unit_price) AS minimum_unit_price FROM sales_data;

-- 5. Calculate the total quantity of products sold.
SELECT SUM(quantity) FROM sales_data WHERE order_status = 'Delivered';

-- Section B – GROUP BY
-- Focus: Grouping and aggregate calculations.

-- 6. Find the total number of orders placed by each customer.
SELECT customer_name,COUNT(customer_name) FROM sales_data GROUP BY customer_name ORDER BY customer_name ASC;

-- 7. Calculate the total revenue generated by each product category.
SELECT category, SUM(quantity * unit_price * (100 - discount_percent)/100) AS total_revenue_generated FROM sales_data GROUP BY category ORDER BY category ASC;

-- 8. Find the average product price for each category.
SELECT category, AVG(unit_price) AS average_product_price FROM sales_data GROUP BY category ORDER BY category ASC;

-- 9. Find the total number of orders placed in each city.
SELECT city, COUNT(order_id) AS placed_order FROM sales_data GROUP BY city ORDER BY city ASC;

-- 10. Calculate the total quantity sold for each product.
SELECT product_name, SUM(quantity) as product_sold FROM sales_data GROUP BY product_name ORDER BY product_name ASC;

-- 11. Find the number of orders for each payment method.
SELECT payment_method, COUNT(order_id) AS number_of_orders FROM sales_data GROUP BY payment_method;

-- 12. Find the average customer rating for each product category.
SELECT category, AVG(rating) AS customer_rating FROM sales_data GROUP BY category;







